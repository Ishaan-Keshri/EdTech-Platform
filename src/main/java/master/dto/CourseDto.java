package master.dto;

public class CourseDto {
	private String cid;
	private String cname;
	private String iname;
	private String sname;
	private String cdue;
	private String cdis;
	private String cmat;
	private String cvideo;
	public String getCid() {
		return cid;
	}
	public void setCid(String cid) {
		this.cid = cid;
	}
	public String getCname() {
		return cname;
	}
	public void setCname(String cname) {
		this.cname = cname;
	}
	public String getIname() {
		return iname;
	}
	public void setIname(String iname) {
		this.iname = iname;
	}
	public String getSname() {
		return sname;
	}
	public void setSname(String sname) {
		this.sname = sname;
	}
	public String getCdue() {
		return cdue;
	}
	public void setCdue(String cdue) {
		this.cdue = cdue;
	}
	public String getCdis() {
		return cdis;
	}
	public void setCdis(String cdis) {
		this.cdis = cdis;
	}
	public String getCmat() {
		return cmat;
	}
	public void setCmat(String cmat) {
		this.cmat = cmat;
	}
	public String getCvideo() {
		return cvideo;
	}
	public void setCvideo(String cvideo) {
		this.cvideo = cvideo;
	}
}
